/** localStorage that never throws (private mode, blocked storage…). */
export const storage = {
  get(key) {
    try {
      return localStorage.getItem(key);
    } catch {
      return null;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(key, value);
    } catch {
      // Not critical: preferences just won't persist.
    }
  },
};
